"""Independent-model and longitudinal reviews, plus evaluation preparation.

Distances are connection proposals only. No probability fusion, inferred lesion
growth or clinical pass/fail can be generated by these bookkeeping tools.
"""
from datetime import datetime
import hashlib
import json
import math
import re
from uuid import uuid4
import numpy as np
from .workflow import Workflow, audit


def fingerprint(result):
    """Identity is original content and instances, not an image display index."""
    sources=result.get('source',{}).get('sources',[])
    if not sources: raise ValueError('원본 출처가 없어 연결할 수 없습니다.')
    return sorted((s['instance_id'],s['sha256']) for s in sources)


def candidate_rows(run,result):
    return [{**f,'ref':run['id']+'/'+f['id'],'run_id':run['id'],'model_id':run['model_id']} for f in result.get('findings',[])]


class ExtendedWorkflow(Workflow):
    def save(self,table,study_id,payload,parent_id=None,prior_study=None):
        identifier=str(uuid4())
        with self.store.connect() as c:
            if table=='longitudinal_versions':
                c.execute('INSERT INTO longitudinal_versions(id,current_study,prior_study,payload) VALUES (?,?,?,?)',(identifier,study_id,prior_study,json.dumps(payload,ensure_ascii=False,allow_nan=False)))
            else:
                c.execute('INSERT INTO model_comparison_versions(id,study_id,parent_id,payload) VALUES (?,?,?,?)',(identifier,study_id,parent_id,json.dumps(payload,ensure_ascii=False,allow_nan=False)))
            audit(c,table+'_saved',identifier,study_id,{'parent_id':parent_id})
        return {**self.row(table,identifier),'payload':payload}

    def completed(self,identifier):
        run=self.analysis.get(identifier)
        if run['status']!='completed': raise ValueError('완료된 분석 결과만 비교할 수 있습니다.')
        return run,self.analysis.result(identifier)

    def compare_models(self,study_id,run_ids):
        if len(run_ids)!=2 or len(set(run_ids))!=2: raise ValueError('독립 결절 모델 실행 두 개를 선택해 주세요.')
        pairs=[self.completed(rid) for rid in run_ids]
        if {r['model_id'] for r,_ in pairs}!={'lung_nodules','monai_nodule'}: raise ValueError('TotalSegmentator와 MONAI 결절 모델을 각각 선택해 주세요.')
        if len({r['series_id'] for r,_ in pairs})!=1 or any(self.row('series',r['series_id'])['study_id']!=study_id for r,_ in pairs): raise ValueError('동일 검사/시리즈에서 실행한 모델만 연결할 수 있습니다.')
        if fingerprint(pairs[0][1])!=fingerprint(pairs[1][1]): raise ValueError('모델의 원본 출처가 다릅니다.')
        groups=[candidate_rows(r,result) for r,result in pairs]
        edges=[]
        for left in groups[0]:
            for right in groups[1]:
                distance=float(np.linalg.norm(np.array(left['centroid_lps_mm'])-right['centroid_lps_mm']))
                if distance<=10:
                    edges.append({'left':left['ref'],'right':right['ref'],'state':'proposed','distance_mm':distance,'reason':'중심 거리 10 mm 이내; 동일 병변 여부는 사용자 확인 필요'})
        return self.save('model_comparison_versions',study_id,{'runs':[r for r,_ in pairs],'groups':groups,'edges':edges,
                    'limitations':['모델별 점수는 독립적인 모델 출력이며 악성 확률이 아닙니다.','박스와 분할의 측정값은 같은 의미가 아니며 점수를 평균하지 않습니다.','미연결/후보 없음은 정상 판정이 아닙니다.']})

    def model_links(self,identifier,edges):
        old=self.row('model_comparison_versions',identifier);payload=json.loads(old['payload'])
        groups=[{f['ref']:f for f in group} for group in payload['groups']];seen=set();clean=[]
        for edge in edges:
            key=(edge.get('left'),edge.get('right'))
            if key in seen or key[0] not in groups[0] or key[1] not in groups[1]: raise ValueError('다른 실행/중복 후보 연결입니다.')
            seen.add(key)
            if edge.get('state') not in {'confirmed','rejected','proposed'} or not isinstance(edge.get('reason'),str) or not edge['reason'].strip(): raise ValueError('연결 상태와 근거를 입력해 주세요.')
            clean.append({k:edge[k] for k in ['left','right','state','reason']})
        payload['edges']=clean
        return self.save('model_comparison_versions',old['study_id'],payload,identifier)

    def longitudinal(self,study_id,prior_study,current_run,prior_run,links,same_patient_confirmed,landmarks):
        current=self.row('studies',study_id);prior=self.row('studies',prior_study)
        if study_id==prior_study or not same_patient_confirmed: raise ValueError('서로 다른 검사이며 동일 환자의 이전 CT임을 사용자가 확인해야 합니다.')
        try: days=(datetime.strptime(current['study_date'],'%Y%m%d')-datetime.strptime(prior['study_date'],'%Y%m%d')).days
        except (ValueError,TypeError): raise ValueError('두 검사의 원본 DICOM 촬영일이 필요합니다.')
        if days<=0: raise ValueError('이전 검사의 촬영일이 현재 검사보다 앞서야 합니다.')
        cr,cv=self.completed(current_run);pr,pv=self.completed(prior_run)
        if self.row('series',cr['series_id'])['study_id']!=study_id or self.row('series',pr['series_id'])['study_id']!=prior_study: raise ValueError('선택 검사에 속하지 않는 실행입니다.')
        # LPS from different acquisitions has no automatic anatomical identity.
        registration={'status':'not_registered','matrix_lps':None,'rms_mm':None,'use':'측정 연결은 사용자 확인; 영상 정렬 미적용'}
        if landmarks:
            points=np.asarray(landmarks,dtype=float)
            if points.ndim!=3 or points.shape[1:]!=(2,3) or not 3<=len(points)<=30 or not np.all(np.isfinite(points)): raise ValueError('현재/이전 LPS 점 쌍 3~30개가 필요합니다.')
            # Fit prior -> current rigid transform, never scale diameters/volumes.
            target,source=points[:,0],points[:,1];a=source-source.mean(0);b=target-target.mean(0)
            if np.linalg.matrix_rank(a)<2 or np.linalg.matrix_rank(b)<2: raise ValueError('일직선이 아닌 기준점이 필요합니다.')
            u,_,vt=np.linalg.svd(a.T@b);rotation=vt.T@u.T
            if np.linalg.det(rotation)<0: vt[-1]*=-1;rotation=vt.T@u.T
            translation=target.mean(0)-rotation@source.mean(0);matrix=np.eye(4);matrix[:3,:3]=rotation;matrix[:3,3]=translation
            rms=float(np.sqrt(np.mean(np.sum((source@rotation.T+translation-target)**2,axis=1))))
            registration={'status':'manual_rigid_fit','matrix_lps':matrix.tolist(),'rms_mm':rms,'landmarks':landmarks,'use':'사용자 기준점 적합; 호흡/변형 보정 및 자동 병변 확인 아님'}
        cands={f['ref']:f for f in candidate_rows(cr,cv)};priors={f['ref']:f for f in candidate_rows(pr,pv)};rows=[];seen=set()
        for link in links:
            key=(link.get('current_ref'),link.get('prior_ref'))
            if key in seen or key[0] not in cands or key[1] not in priors: raise ValueError('이전/현재 후보 연결이 유효하지 않습니다.')
            seen.add(key)
            if link.get('confirmed') is not True or not isinstance(link.get('reason'),str) or not link['reason'].strip(): raise ValueError('각 병변 연결의 사용자 확인과 근거가 필요합니다.')
            now,then=cands[key[0]],priors[key[1]];changes={}
            same_model=cr['model_id']==pr['model_id'] and cr.get('snapshot',{}).get('configuration')==pr.get('snapshot',{}).get('configuration') and cr.get('snapshot',{}).get('runtime',{}).get('weights_digest')==pr.get('snapshot',{}).get('runtime',{}).get('weights_digest')
            for field in ['diameter_mm','volume_mm3']:
                x,y=now.get(field),then.get(field)
                method_ok=(field!='diameter_mm' or now.get('diameter_method')==then.get('diameter_method'))
                valid=registration['status']=='manual_rigid_fit' and same_model and now.get('kind')==then.get('kind') and method_ok and isinstance(x,(int,float)) and isinstance(y,(int,float)) and math.isfinite(x) and math.isfinite(y) and y>0
                changes[field]={'status':'comparable' if valid else 'not_comparable','current':x,'prior':y,
                                'delta':x-y if valid else None,'percent':100*(x-y)/y if valid else None,
                                'limitation':'모델·측정법/수치 확인 필요. 변화 수치는 성장/악성 판정이 아닙니다.'}
            rows.append({**link,'current':now,'prior':then,'changes':changes})
        payload={'current_study':current,'prior_study':prior,'days':days,'current_run':cr,'prior_run':pr,'registration':registration,'links':rows,'same_patient_user_confirmed':True,'clinical_validation':'not_evaluated'}
        return self.save('longitudinal_versions',study_id,payload,prior_study=prior_study)

    def evaluation_case(self,study_id,split,reference_source,reviewer,payload):
        """A prepared case is not an expert-validated outcome or a clinical pass."""
        self.row('studies',study_id)
        if split not in {'development','validation','test'}: raise ValueError('데이터 분할을 확인해 주세요.')
        with self.store.connect() as c:
            hashes=sorted(r[0] for r in c.execute('SELECT i.sha256 FROM instances i JOIN series s ON s.id=i.series_id WHERE s.study_id=?',(study_id,)))
            if not hashes: raise ValueError('원본 DICOM이 있어야 평가 사례로 등록할 수 있습니다.')
            source_hash=hashlib.sha256(json.dumps(hashes).encode()).hexdigest()
            for old in c.execute('SELECT split,payload FROM evaluation_cases'):
                existing=json.loads(old['payload'])
                same_group=bool(payload.get('patient_group')) and payload.get('patient_group')==existing.get('patient_group')
                if (set(existing.get('instance_hashes',[]))&set(hashes) or same_group) and old['split']!=split: raise ValueError('같은 원본/환자 그룹이 다른 평가 분할에 포함되어 있습니다.')
            evaluated=payload.get('expert_reviewed') is True
            counts=payload.get('counts',{})
            if evaluated and (not reference_source.strip() or not reviewer.strip() or not re.fullmatch('[0-9a-f]{64}',str(payload.get('reference_sha256',''))) or not payload.get('patient_group') or not counts): raise ValueError('전문 검토자·정답 출처/SHA-256·비식별 환자 그룹·종류별 TP/FP/FN이 필요합니다.')
            for kind,value in counts.items():
                if kind not in {'nodule','pleural_effusion','pericardial_effusion'} or set(value)!={'tp','fp','fn'} or any(type(n) is not int or n<0 for n in value.values()): raise ValueError('평가 종류별 음수가 아닌 정수 TP/FP/FN을 입력해 주세요.')
            data={**payload,'source_hash':source_hash,'instance_hashes':hashes,'status':'reviewed_counts' if evaluated else 'prepared','clinical_acceptance':'not_established'}
            identifier=str(uuid4());c.execute('INSERT INTO evaluation_cases(id,study_id,split,reference_source,reviewer,payload) VALUES (?,?,?,?,?,?)',(identifier,study_id,split,reference_source,reviewer,json.dumps(data,ensure_ascii=False)))
            audit(c,'evaluation_case_saved',identifier,study_id,{'split':split,'status':data['status']})
        return {'id':identifier,'payload':data}

    def evaluation_summary(self):
        with self.store.connect() as c: cases=[{**dict(r),'payload':json.loads(r['payload'])} for r in c.execute('SELECT * FROM evaluation_cases ORDER BY created_at DESC,rowid DESC')]
        # Revisions of the same source are not independent samples.
        latest={}
        for case in cases: latest.setdefault(case['payload']['source_hash'],case)
        metrics={}
        for split in ['development','validation','test']:
            rows=[r for r in latest.values() if r['split']==split and r['payload']['status']=='reviewed_counts']
            result={}
            for kind in ['nodule','pleural_effusion','pericardial_effusion']:
                measured=[r['payload']['counts'][kind] for r in rows if kind in r['payload'].get('counts',{})]
                totals={k:sum(m[k] for m in measured) for k in ['tp','fp','fn']}
                tp,fp,fn=(totals[k] for k in ['tp','fp','fn'])
                result[kind]={**totals,'cases':len(measured),'sensitivity':tp/(tp+fn) if tp+fn else None,'precision':tp/(tp+fp) if tp+fp else None,'false_positives_per_case':fp/len(measured) if measured else None}
            metrics[split]=result
        return {'cases':cases,'metrics':metrics,'clinical_acceptance':'not_established','limitations':['정답/검토자와 독립 테스트·조영 프로토콜별 평가를 확보하기 전 진료 성능 완료 아님.','사례별 수기는 사용자 입력이며 병변 일치 기준/검토 절차를 별도 기록해야 합니다.']}
